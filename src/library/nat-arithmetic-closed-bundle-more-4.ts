import { Term, Nat, Zero, app, eq, refl } from '../syntax/ast';
import { numeral, addTerm } from './nat';
import { mulTerm } from './mul';
import { powTerm } from './pow';
import { pred } from './pred';
import { sub } from './sub';
const eqNat = (a: Term, b: Term): Term => eq(Nat, a, b);
const subTerm = (a: Term, b: Term): Term => app(app(sub, a), b);
const proof = (n: number): Term => refl(Nat, numeral(n));
export const addTwentyThreeNineteenType = eqNat(addTerm(numeral(23), numeral(19)), numeral(42));
export const addTwentyThreeNineteenProof = proof(42);
export const productSevenSevenType = eqNat(mulTerm(numeral(7), numeral(7)), numeral(49));
export const productSevenSevenProof = proof(49);
export const powTwoSixType = eqNat(powTerm(numeral(2), numeral(6)), numeral(64));
export const powTwoSixProof = proof(64);
export const mixedSmallType = eqNat(addTerm(mulTerm(numeral(5), numeral(6)), numeral(4)), numeral(34));
export const mixedSmallProof = proof(34);
export const predAddType = eqNat(app(pred, addTerm(numeral(18), numeral(7))), numeral(24));
export const predAddProof = proof(24);
export const subProductType = eqNat(subTerm(mulTerm(numeral(6), numeral(6)), numeral(11)), numeral(25));
export const subProductProof = proof(25);
export const zeroSubAddType = eqNat(subTerm(Zero, addTerm(numeral(4), numeral(3))), Zero);
export const zeroSubAddProof = proof(0);
