import { Term, Nat, prod, pair, app, eq, refl } from '../syntax/ast';
import { rotate90 } from './geometry-rotations';
import { translate } from './geometry-transform';
import { normSq, dot2 } from './geometry-metrics';
import { cross2 } from './geometry-cross';
import { midpoint } from './geometry-segment';
import { onCircle } from './geometry-circle';
import { numeral } from './nat';

export const Point2: Term = prod(Nat, Nat);
const d = pair(numeral(2), numeral(1));
const t = (p: Term): Term => app(app(translate, app(rotate90, p)), d);
const a=t(pair(numeral(1),numeral(1))); const b=t(pair(numeral(2),numeral(2))); const c=t(pair(numeral(3),numeral(3)));
const e=t(pair(numeral(4),numeral(4))); const f=t(pair(numeral(5),numeral(5))); const g=t(pair(numeral(6),numeral(6)));
const m=app(app(midpoint,b),e);
export const aType: Term=eq(Point2,a,pair(numeral(3),numeral(2))); export const aProof: Term=refl(Point2,pair(numeral(3),numeral(2)));
export const bType: Term=eq(Point2,b,pair(numeral(4),numeral(3))); export const bProof: Term=refl(Point2,pair(numeral(4),numeral(3)));
export const cType: Term=eq(Point2,c,pair(numeral(5),numeral(4))); export const cProof: Term=refl(Point2,pair(numeral(5),numeral(4)));
export const eType: Term=eq(Point2,e,pair(numeral(6),numeral(5))); export const eProof: Term=refl(Point2,pair(numeral(6),numeral(5)));
export const fType: Term=eq(Point2,f,pair(numeral(7),numeral(6))); export const fProof: Term=refl(Point2,pair(numeral(7),numeral(6)));
export const gType: Term=eq(Point2,g,pair(numeral(8),numeral(7))); export const gProof: Term=refl(Point2,pair(numeral(8),numeral(7)));
export const midpointType: Term=eq(Point2,m,pair(numeral(4),numeral(5))); export const midpointProof: Term=refl(Point2,pair(numeral(4),numeral(5)));
export const gNormType: Term=eq(Nat,app(normSq,g),numeral(113)); export const gNormProof: Term=refl(Nat,numeral(113));
export const gCircleType: Term=app(app(onCircle,g),pair(g,numeral(113))); export const gCircleProof: Term=refl(Nat,numeral(113));
export const aNormType: Term=eq(Nat,app(normSq,a),numeral(13)); export const aNormProof: Term=refl(Nat,numeral(13));
export const cNormType: Term=eq(Nat,app(normSq,c),numeral(41)); export const cNormProof: Term=refl(Nat,numeral(41));
export const bMidpointType: Term=eq(Point2,app(app(midpoint,a),g),pair(numeral(3),numeral(7))); export const bMidpointProof: Term=refl(Point2,pair(numeral(3),numeral(7)));
export const fNormType: Term=eq(Nat,app(normSq,f),numeral(85)); export const fNormProof: Term=refl(Nat,numeral(85));
export const acDotType: Term=eq(Nat,app(app(dot2,a),c),numeral(23)); export const acDotProof: Term=refl(Nat,numeral(23));
export const ceCrossType: Term=eq(Nat,app(app(cross2,c),e),numeral(49)); export const ceCrossProof: Term=refl(Nat,numeral(49));
