import { Term, Nat, prod, pair, app, eq, refl } from '../syntax/ast';
import { scaleVec } from './geometry-scalar';
import { rotate90 } from './geometry-rotations';
import { translate } from './geometry-transform';
import { normSq, dot2 } from './geometry-metrics';
import { cross2 } from './geometry-cross';
import { midpoint } from './geometry-segment';
import { numeral } from './nat';

export const Point2: Term = prod(Nat, Nat);
const k = numeral(2); const d = pair(numeral(1), numeral(1));
const transform = (p: Term): Term => app(app(translate, app(rotate90, app(app(scaleVec, k), p))), d);
const a = transform(pair(numeral(1), numeral(2)));
const b = transform(pair(numeral(2), numeral(1)));
const c = transform(pair(numeral(3), numeral(2)));
const m = app(app(midpoint, a), b);
export const aType: Term = eq(Point2, a, pair(numeral(5), numeral(3)));
export const aProof: Term = refl(Point2, pair(numeral(5), numeral(3)));
export const bType: Term = eq(Point2, b, pair(numeral(3), numeral(5)));
export const bProof: Term = refl(Point2, pair(numeral(3), numeral(5)));
export const cType: Term = eq(Point2, c, pair(numeral(5), numeral(7)));
export const cProof: Term = refl(Point2, pair(numeral(5), numeral(7)));
export const midpointType: Term = eq(Point2, m, pair(numeral(5), numeral(5)));
export const midpointProof: Term = refl(Point2, pair(numeral(5), numeral(5)));
export const aNormType: Term = eq(Nat, app(normSq, a), numeral(34));
export const aNormProof: Term = refl(Nat, numeral(34));
export const abDotType: Term = eq(Nat, app(app(dot2, a), b), numeral(30));
export const abDotProof: Term = refl(Nat, numeral(30));
export const acCrossType: Term = eq(Nat, app(app(cross2, a), c), numeral(50));
export const acCrossProof: Term = refl(Nat, numeral(50));
