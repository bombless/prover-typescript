import { Term, Nat, prod, pair, app, eq, refl } from '../syntax/ast';
import { rotate90 } from './geometry-rotations';
import { translate } from './geometry-transform';
import { midpoint } from './geometry-segment';
import { normSq, dot2 } from './geometry-metrics';
import { cross2 } from './geometry-cross';
import { onCircle } from './geometry-circle';
import { incidence } from './geometry-incidence';
import { onVerticalLine } from './geometry-line';
import { numeral } from './nat';

export const Point2: Term = prod(Nat, Nat);
const transform = (p: Term): Term => app(app(translate, app(rotate90, p)), pair(numeral(2), numeral(1)));
const p = transform(pair(numeral(1), numeral(1)));
const q = transform(pair(numeral(2), numeral(2)));
const r = transform(pair(numeral(3), numeral(1)));
const s = transform(pair(numeral(4), numeral(2)));
const m = app(app(midpoint, p), r);
const line = pair(pair(numeral(4), numeral(0)), pair(numeral(1), numeral(0)));

export const pType: Term = eq(Point2, p, pair(numeral(3), numeral(2)));
export const pProof: Term = refl(Point2, pair(numeral(3), numeral(2)));
export const qType: Term = eq(Point2, q, pair(numeral(4), numeral(3)));
export const qProof: Term = refl(Point2, pair(numeral(4), numeral(3)));
export const rType: Term = eq(Point2, r, pair(numeral(3), numeral(4)));
export const rProof: Term = refl(Point2, pair(numeral(3), numeral(4)));
export const sType: Term = eq(Point2, s, pair(numeral(4), numeral(5)));
export const sProof: Term = refl(Point2, pair(numeral(4), numeral(5)));
export const pNormType: Term = eq(Nat, app(normSq, p), numeral(13));
export const pNormProof: Term = refl(Nat, numeral(13));
export const qNormType: Term = eq(Nat, app(normSq, q), numeral(25));
export const qNormProof: Term = refl(Nat, numeral(25));
export const pqDotType: Term = eq(Nat, app(app(dot2, p), q), numeral(18));
export const pqDotProof: Term = refl(Nat, numeral(18));
export const pqCrossType: Term = eq(Nat, app(app(cross2, p), q), numeral(17));
export const pqCrossProof: Term = refl(Nat, numeral(17));
export const midpointType: Term = eq(Point2, m, pair(numeral(3), numeral(4)));
export const midpointProof: Term = refl(Point2, pair(numeral(3), numeral(4)));
export const midpointCircleType: Term = app(app(onCircle, m), pair(m, numeral(25)));
export const midpointCircleProof: Term = refl(Nat, numeral(25));
export const qIncidenceType: Term = app(app(incidence, q), line);
export const qIncidenceProof: Term = refl(Nat, numeral(4));
export const rVerticalType: Term = app(app(onVerticalLine, r), numeral(3));
export const rVerticalProof: Term = refl(Nat, numeral(3));
