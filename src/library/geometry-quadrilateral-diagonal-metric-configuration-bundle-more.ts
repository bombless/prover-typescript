import { Term, Nat, prod, pair, app, eq, refl } from '../syntax/ast';
import { rotate90 } from './geometry-rotations';
import { translate } from './geometry-transform';
import { midpoint } from './geometry-segment';
import { distanceSq } from './geometry-distance';
import { normSq } from './geometry-metrics';
import { numeral } from './nat';
export const Point2: Term = prod(Nat, Nat);
const t=(p:Term)=>app(app(translate,app(rotate90,p)),pair(numeral(1),numeral(2)));
const a=t(pair(numeral(1),numeral(1))); const b=t(pair(numeral(2),numeral(3))); const c=t(pair(numeral(4),numeral(2))); const d=t(pair(numeral(5),numeral(4)));
const m=app(app(midpoint,a),c);
const e1=eq(Point2,a,pair(numeral(2),numeral(3)));
const e2=eq(Point2,b,pair(numeral(4),numeral(4)));
const e3=eq(Point2,c,pair(numeral(3),numeral(6)));
const e4=eq(Point2,d,pair(numeral(5),numeral(7)));
const e5=eq(Point2,m,pair(numeral(2),numeral(6)));
const e6=eq(Nat,app(app(distanceSq,a),b),numeral(20));
const e7=eq(Nat,app(normSq,m),numeral(40));
export const quadrilateralDiagonalMetricBundleType: Term=prod(e1,prod(e2,prod(e3,prod(e4,prod(e5,prod(e6,e7))))));
export const quadrilateralDiagonalMetricBundleProof: Term=pair(refl(Point2,pair(numeral(2),numeral(3))),pair(refl(Point2,pair(numeral(4),numeral(4))),pair(refl(Point2,pair(numeral(3),numeral(6))),pair(refl(Point2,pair(numeral(5),numeral(7))),pair(refl(Point2,pair(numeral(2),numeral(6))),pair(refl(Nat,numeral(20)),refl(Nat,numeral(40))))))));
